"""Fresh-process use of a saved adapter; never manually repairs model output."""
import argparse
import gc
import hashlib
import json
import random
from pathlib import Path
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM
from peft import PeftModel
from modeling_lab.operations import validate_plan
from modeling_lab.operate import run_blender
from modeling_training.corpus import wrapped
from modeling_training.finetune import prompt_tokens, configure_profile


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--base', required=True)
    p.add_argument('--adapter', required=True)
    p.add_argument('--prompt', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--input')
    p.add_argument('--editable')
    p.add_argument('--render', action='store_true')
    p.add_argument('--profile', choices=['modeling', 'vfx', 'intent','scene_intent'], default='modeling',
                   help='Use the same system instructions as the adapter training run')
    p.add_argument('--blender', default=r'C:\Program Files\Blender Foundation\Blender 5.1\blender.exe')
    args = p.parse_args()
    configure_profile(args.profile)
    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    source = Path(args.input).resolve() if args.input else None
    source_hash = hashlib.sha256(source.read_bytes()).hexdigest() if source else None
    if source and not args.editable:
        p.error('Input requires one explicit editable mesh name')
    request = {**vars(args), 'input_sha256': source_hash,
               'adapter_sha256': hashlib.sha256((Path(args.adapter)/'adapter_model.safetensors').read_bytes()).hexdigest(),
               'base_source': json.loads((Path(args.base)/'source-manifest.json').read_text()),
               'scope': 'Single-operation adapter inference; supplied humanoid anatomy and rig are not generated by this model'}
    (output/'request.json').write_text(json.dumps(request, indent=2))
    try:
        model_prompt=args.prompt
        scene_catalog=None
        if args.profile=='scene_intent':
            if source is None:
                raise ValueError('Scene-aware inference requires an existing source scene')
            inventory_path=output/'source-inventory.json'
            # Observe candidate names independently of the separately enforced edit authorization.
            run_blender(args.blender,['--input',str(source),'--inventory',str(inventory_path)],output/'inventory.log')
            inventory=json.loads(inventory_path.read_text())
            scene_catalog=[dict(name=o['id'],type='MESH') for o in inventory['objects']]
            order_seed=int(hashlib.sha256((source_hash+args.prompt).encode()).hexdigest()[:16],16)
            random.Random(order_seed).shuffle(scene_catalog)
            from modeling_training.scene_intent_ops import prompt as scene_prompt
            model_prompt=scene_prompt(args.prompt,scene_catalog)
            (output/'model-input.json').write_text(model_prompt,encoding='utf-8')
            request['model_input_sha256']=hashlib.sha256((output/'model-input.json').read_bytes()).hexdigest()
            request['observed_inventory_sha256']=hashlib.sha256(inventory_path.read_bytes()).hexdigest()
            request['catalog_order_seed']=order_seed
            (output/'request.json').write_text(json.dumps(request,indent=2),encoding='utf-8')
            if hashlib.sha256(source.read_bytes()).hexdigest()!=source_hash:
                raise RuntimeError('Original source changed during inventory')
        torch.set_num_threads(4)
        tokenizer = AutoTokenizer.from_pretrained(args.adapter, local_files_only=True)
        base = AutoModelForCausalLM.from_pretrained(args.base, torch_dtype=torch.float16,
                                                  local_files_only=True, trust_remote_code=False, attn_implementation='sdpa').to('cuda')
        model = PeftModel.from_pretrained(base, args.adapter, is_trainable=False).eval()
        model.generation_config.temperature = None
        model.generation_config.top_p = None
        model.generation_config.top_k = None
        ids = torch.tensor([prompt_tokens(tokenizer, model_prompt)], device='cuda')
        with torch.no_grad():
            generated = model.generate(input_ids=ids, attention_mask=torch.ones_like(ids), do_sample=False,
                                       max_new_tokens=192, pad_token_id=tokenizer.eos_token_id)
        raw = tokenizer.decode(generated[0, ids.shape[1]:], skip_special_tokens=True).strip()
        (output/'response.json').write_text(json.dumps({'raw': raw, 'fresh_process_adapter_loaded': True}, indent=2))
        operation = json.loads(raw)
        if args.profile == 'scene_intent':
            from modeling_training.scene_intent_ops import compile_intent
            (output/'intent.json').write_text(json.dumps(operation,indent=2))
            operation=compile_intent(operation,scene_catalog)
        elif args.profile == 'intent':
            from modeling_training.intent_ops import compile_intent
            (output/'intent.json').write_text(json.dumps(operation, indent=2))
            operation = compile_intent(operation, [args.editable] if source else [])
        plan = validate_plan(wrapped(operation), [args.editable] if source else [])
        (output/'plan.json').write_text(json.dumps(plan, indent=2))
        del model, base, ids, generated
        gc.collect()
        torch.cuda.empty_cache()
        flags = ['--input', str(source), '--editable', args.editable] if source else []
        flags += ['--plan', str(output/'plan.json'), '--output', str(output/'scene')]
        if args.render:
            flags.append('--render')
        run_blender(args.blender, flags, output/'blender.log')
        run_blender(args.blender, ['--input', str(output/'scene/model.blend'), '--verify', str(output/'reopen.json')], output/'reopen.log')
        if source and hashlib.sha256(source.read_bytes()).hexdigest() != source_hash:
            raise RuntimeError('Original source changed')
        status = {'status': 'completed', 'scope': 'Structural execution and fresh reload; semantic and artistic review separate'}
    except Exception as exc:
        (output/'status.json').write_text(json.dumps({'status': 'failed', 'error': str(exc)}, indent=2))
        raise
    (output/'status.json').write_text(json.dumps(status, indent=2))
    print(json.dumps(status), flush=True)


if __name__ == '__main__':
    main()
